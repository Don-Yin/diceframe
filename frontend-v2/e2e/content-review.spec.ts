import { expect, test } from './fixtures'
import { accessToken } from './support'

test('edited text fragments save into all four real content libraries', async ({ page, request }, info) => {
  test.setTimeout(90_000)
  const suffix = info.project.name
  await page.goto('/#/adventures')
  await page.locator('.adventure-header-more > summary').click()
  await page.getByRole('button', { name: '文本整理与分配', exact: true }).click()
  await page.getByTestId('text-source').fill(`# Review World ${suffix}\nDense fog.\n# Review Keeper ${suffix}\nFriendly keeper.\n# Review Book ${suffix}\nLost bell.\n# Review Quest ${suffix}\nFind the bell.`)
  await page.getByTestId('text-preview').click()
  await expect(page.getByTestId('fragment-target')).toHaveCount(4)
  await page.getByTestId('fragment-target').nth(0).selectOption('world')
  await page.getByTestId('fragment-target').nth(1).selectOption('character_template')
  await page.getByTestId('fragment-target').nth(3).selectOption('adventure')
  await page.getByTestId('fragment-text').nth(1).fill('Reviewed keeper background.')
  await page.getByTestId('text-reviewed').check()
  await expect(page.getByTestId('text-commit')).toBeDisabled()
  await page.getByTestId('text-validate').click()
  await page.getByTestId('text-reviewed').check()
  await expect(page.getByTestId('text-commit')).toBeEnabled()
  const response = page.waitForResponse(response => response.url().endsWith('/api/content-review/commit'))
  await page.getByTestId('text-commit').click()
  const result = await (await response).json()
  expect(result.ok, JSON.stringify(result)).toBe(true)
  await expect(page.getByTestId('text-results')).toContainText('已保存')
  const geometry = await page.locator('.text-review').evaluate(element => ({ overflow: element.scrollWidth - element.clientWidth, right: element.getBoundingClientRect().right, width: innerWidth }))
  expect(geometry.overflow).toBeLessThanOrEqual(1)
  expect(geometry.right).toBeLessThanOrEqual(geometry.width)
  await page.screenshot({ path: info.outputPath('content-review.png'), fullPage: true })
  const headers = { Authorization: `Bearer ${accessToken()}` }
  const worlds = await (await request.get('/api/worlds', { headers })).json()
  expect(worlds.worlds.some((world: { name: string }) => world.name === `Review World ${suffix}`)).toBe(true)
  const cards = await (await request.get('/api/character-cards', { headers })).json()
  expect(cards.cards.find((card: { character_name: string }) => card.character_name === `Review Keeper ${suffix}`).background).toBe('Reviewed keeper background.')
  const books = await (await request.get('/api/lorebooks', { headers })).json()
  expect(books.books.some((book: { name: string }) => book.name === `Review Book ${suffix}`)).toBe(true)
  await page.reload()
  await expect(page.locator('.adventure-package-card').filter({ has: page.getByRole('heading', { name: `Review Quest ${suffix}`, exact: true }) })).toBeVisible()
})
