import { expect, test } from './fixtures'
import { accessToken } from './support'

test('GM configures one seat, refreshes it and player projection hides the settings', async ({ page, request }, info) => {
  const key = 'web|e2e-room|web_bot'
  const headers = { Authorization: `Bearer ${accessToken()}`, 'X-TRPG-Confirm': 'true' }
  const base = `/api/games/${encodeURIComponent(key)}/ai-seats`
  await page.goto(`/#/play?game=${encodeURIComponent(key)}`)
  const gmToggle = page.getByTestId('play-gm-toggle')
  await expect(gmToggle).toHaveAttribute('aria-expanded', 'false')
  await gmToggle.click()
  await expect(gmToggle).toHaveAttribute('aria-expanded', 'true')
  await page.getByTestId('gm-workspace').getByRole('tab', { name: '队伍', exact: true }).click()
  const panel = page.getByTestId('ai-seats')
  await expect(panel).toBeVisible()
  await panel.getByTestId('configure-e2e-player').click()
  await page.getByTestId('provider').selectOption('e2e-provider')
  await page.getByTestId('model').selectOption('e2e-chat')
  await page.getByTestId('style').selectOption('cautious')
  const dialog = page.locator('.ai-seat-dialog')
  const geometry = await dialog.evaluate(element => ({ overflow: element.scrollWidth - element.clientWidth,
    right: element.getBoundingClientRect().right, viewport: window.innerWidth }))
  expect(geometry.overflow).toBeLessThanOrEqual(1)
  expect(geometry.right).toBeLessThanOrEqual(geometry.viewport)
  await page.screenshot({ path: info.outputPath('ai-seat-editor.png'), fullPage: true })
  await page.getByTestId('save').click()
  await expect(dialog).toHaveCount(0)
  const saved = await (await request.get(base, { headers })).json()
  expect(saved.seats['e2e-player'].model).toBe('e2e-chat')
  expect(saved.seats['e2e-player'].style).toBe('cautious')
  expect(saved.seats['e2e-player'].inherits).toBe(false)
  expect(JSON.stringify(saved)).not.toContain('base_url')
  expect(JSON.stringify(saved)).not.toContain('api_key')
  await page.reload()
  const reloadedGmToggle = page.getByTestId('play-gm-toggle')
  await expect(reloadedGmToggle).toBeVisible()
  if (await reloadedGmToggle.getAttribute('aria-expanded') !== 'true') await reloadedGmToggle.click()
  await expect(reloadedGmToggle).toHaveAttribute('aria-expanded', 'true')
  await page.getByTestId('gm-workspace').getByRole('tab', { name: '队伍', exact: true }).click()
  await expect(panel).toContainText('谨慎')
  await panel.getByTestId('configure-e2e-player').click()
  await expect(page.getByTestId('style')).toHaveValue('cautious')
  await page.locator('.ai-seat-dialog .modal-x').click()
  await page.goto(`/#/play?game=${encodeURIComponent(key)}&user=e2e-player`)
  await expect(page.getByTestId('timeline')).toBeVisible()
  await expect(panel).toHaveCount(0)
  const denied = await request.get(`${base}?user=e2e-player&game=${encodeURIComponent(key)}`, { headers })
  expect(denied.status()).toBe(403)
})
