import { expect, test } from './fixtures'
import { accessToken } from './support'

test('Foundry JSON resources are edited, linked and reviewed before native publishing', async ({ page, request }, info) => {
  test.setTimeout(90_000)
  const name = `Foundry Gate ${info.project.name}`
  const source = { _id: 'GateQuest', name, journal: [{ _id: 'GateJournal', name: 'Gate', pages: [{ _id: 'Page1', type: 'text', text: { content: '<p>A sealed gate.</p>' } }] }], actors: [{ _id: 'Keeper', name: 'Keeper', system: { details: { biography: { value: '<p>A secret keeper.</p>' } } } }], items: [{ _id: 'Key', name: 'Key', system: { description: { value: '<p>A brass key.</p>' } } }] }
  await page.goto('/#/adventures')
  await page.locator('.adventure-header-more > summary').click()
  await page.getByRole('button', { name: '导入剧本 / 外部模组', exact: true }).click()
  await page.locator('.script-review input[type=file]').setInputFiles({ name: 'quest.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(source)) })
  await page.getByTestId('script-preview').click()
  await expect(page.getByTestId('graph-name')).toHaveValue(name)
  await expect(page.getByTestId('script-publish-status')).toContainText('请勾选')
  await page.getByTestId('resource-edit').first().click()
  await page.getByTestId('resource-name').fill('Reviewed resource')
  await page.getByTestId('resource-description').fill('Reviewed reference prose')
  await page.getByTestId('graph-node-description').first().fill('Reviewed gate scene')
  const node = page.locator('.graph-node').first()
  await node.getByTestId('graph-npc-refs').selectOption({ index: 0 })
  await page.getByTestId('script-reviewed').check()
  await expect(page.getByTestId('script-publish')).toBeDisabled()
  await expect(page.getByTestId('script-publish-status')).toContainText('请点击“重新校验”')
  await page.getByTestId('script-validate').click()
  await expect(page.getByTestId('script-publish-status')).toContainText('请勾选')
  await page.getByTestId('script-reviewed').check()
  await expect(page.getByTestId('script-publish')).toBeEnabled()
  await expect(page.getByTestId('script-publish-status')).toContainText('检查已通过，可以保存到你的冒险库')
  const geometry = await page.locator('.adventure-editor-dialog').evaluate(element => ({ overflow: element.scrollWidth - element.clientWidth, right: element.getBoundingClientRect().right, width: window.innerWidth }))
  expect(geometry.overflow).toBeLessThanOrEqual(1)
  expect(geometry.right).toBeLessThanOrEqual(geometry.width)
  await page.getByTestId('script-publish-status').scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('external-review.png'), fullPage: true })
  const response = page.waitForResponse(response => response.url().endsWith('/adventures/script/commit'))
  await page.getByTestId('script-publish').click()
  const result = await (await response).json()
  expect(result.ok, JSON.stringify(result)).toBe(true)
  const headers = { Authorization: `Bearer ${accessToken()}` }
  const detail = await (await request.get(`/api/adventures/${encodeURIComponent(result.adventure_id)}`, { headers })).json()
  expect(detail.adventure.files['adventure.json'].nodes[0].description).toBe('Reviewed gate scene')
  expect(detail.adventure.files['adventure.json'].nodes[0].npc_refs).toHaveLength(1)
  expect(Object.values(detail.adventure.files).some(value => (value as { description?: string }).description === 'Reviewed reference prose')).toBe(true)
  await page.reload()
  await expect(page.locator('.adventure-package-card').filter({ has: page.getByRole('heading', { name, exact: true }) })).toBeVisible()
})
