import { expect, test } from './fixtures'

test('CoC shared reveal presents percentile faces and preserves them after refresh', async ({ page }, info) => {
  await page.goto(`/#/play?game=web%7Ce2e-coc-${info.project.name}%7Cweb_bot`)
  const cards = page.locator('.check-reveal-card')
  await expect(cards.first()).toBeVisible()
  await expect(cards.first().getByTestId('coc-dice-faces')).toHaveCount(0)
  const button = cards.first().locator('.check-reveal-actions button')
  const cardBox = await cards.first().boundingBox()
  const buttonBox = await button.boundingBox()
  expect(Math.abs(buttonBox!.x + buttonBox!.width / 2 - cardBox!.x - cardBox!.width / 2)).toBeLessThanOrEqual(3)
  await cards.first().screenshot({ path: info.outputPath('pending-dice-centered-button.png'), scale: 'css' })
  await cards.first().locator('.check-reveal-actions button').click()
  const faces = cards.first().getByTestId('coc-dice-faces')
  await expect(faces).toContainText('00 + 0 = 100')
  await expect(faces).toContainText('30 + 0 = 30')
  await expect(faces.getByTestId('coc-dice-taken')).toContainText('30')
  await cards.first().locator('summary').click()
  await faces.getByTestId('coc-dice-taken').scrollIntoViewIfNeeded()
  await expect(faces.getByTestId('coc-dice-taken')).toBeInViewport()
  const overflow = await faces.evaluate(element => element.scrollWidth - element.clientWidth)
  expect(overflow).toBeLessThanOrEqual(1)
  await page.screenshot({ path: info.outputPath('coc-percentile-faces.png'), fullPage: true })
  await page.reload()
  await expect(cards.first().getByTestId('coc-dice-taken')).toContainText('30')
})
