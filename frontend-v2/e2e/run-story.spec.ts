import { expect, test } from './fixtures'
import { accessToken } from './support'

test('plan, cancelable preparation, permanent finale, safe export and character carry', async ({ page, request }, testInfo) => {
  test.setTimeout(60_000)
  const viewport = testInfo.project.name === 'mobile' ? 'mobile' : 'desktop'
  const key = `web|e2e-coc-${viewport}|web_bot`, root = `/api/games/${encodeURIComponent(key)}/run-story`
  const headers = { Authorization: `Bearer ${accessToken()}` }
  const initialResponse = await request.get(root, { headers })
  expect(initialResponse.ok()).toBe(true)
  const initial = await initialResponse.json()
  const plan = { format_version: 1, theme: 'Investigation', party_goal: 'Find the missing scholar', mode: 'guided', npc_policy: 'open', core_npcs: [], start: 'arrival', scenes: [
    { id: 'arrival', title: 'Station', kind: 'transition', objective: 'Meet the guide', description: 'Rain at the station', public: true, exit: 'Party leaves the station', next_ids: ['study'], hints: ['A taxi offers a route to the house'] },
    { id: 'study', title: 'Study', kind: 'investigation', objective: 'Find the diary', description: 'A locked study', public: true, exit: 'Diary recovered', next_ids: [], hints: [] },
  ] }
  const adopted = await request.post(`${root}/plan`, { headers, data: { run_id: initial.run_id, revision: 0, plan } })
  expect(adopted.ok()).toBe(true)
  await page.goto(`/#/play?game=${encodeURIComponent(key)}`)
  await expect(page.getByTestId('play-gm-toggle').first()).toBeVisible()
  await page.getByTestId('play-gm-toggle').first().click()
  const workspace = page.getByTestId('gm-workspace')
  await workspace.getByRole('tab', { name: '场景', exact: true }).click()
  const story = workspace.getByTestId('run-story-panel')
  await story.locator(':scope > summary').click()
  await expect(story).toContainText('Meet the guide')
  await story.getByTestId('edit-plan').click()
  await expect(story.getByLabel('主题', { exact: true })).toHaveValue('Investigation')
  await story.getByText('整理为冒险包', { exact: true }).click()
  const packageId = `story_plan_${viewport}`
  await story.getByTestId('story-adventure-id').fill(packageId)
  await story.getByTestId('story-adventure-prepare').click()
  const review = page.getByRole('dialog')
  await expect(review).toBeVisible()
  await expect(review.locator('.graph-node')).toHaveCount(2)
  const firstNodeSelectValues = await review.locator('.graph-node').first().locator('select').evaluateAll(selects => selects.map(select => select.value))
  expect(firstNodeSelectValues).toContain('gm')
  const sceneDescription = review.locator('[data-testid="graph-node-description"]').first()
  await expect(sceneDescription).toHaveValue(/转场条件（GM 确认）/)
  await sceneDescription.fill('Reviewed reusable station scene.')
  const publish = review.getByTestId('script-publish')
  await expect(publish).toBeDisabled()
  await review.getByTestId('script-validate').click()
  await review.getByTestId('script-reviewed').check()
  await expect(publish).toBeEnabled()
  await publish.click()
  await expect(review).toBeHidden()
  const adventures = await (await request.get('/api/adventures?language=zh-CN', { headers })).json()
  const packageEntry = adventures.adventures.find((item: any) => item.adventure_id === `user:${packageId}`)
  expect(packageEntry?.required_runtime).toEqual({ id: 'core:adventure', minimum_version: 1 })
  await page.screenshot({ path: testInfo.outputPath('story-plan.png'), fullPage: false })
  const observer = await page.context().newPage()
  await observer.goto(`/#/play?game=${encodeURIComponent(key)}`)
  await expect(observer.locator('.composer')).toBeVisible()
  const publicFinale = observer.getByTestId('play-chat').getByTestId('run-finale')
  const observerWorkspace = observer.getByTestId('gm-workspace')
  if (!await observerWorkspace.isVisible()) await observer.getByTestId('play-gm-toggle').first().click()
  await observerWorkspace.getByRole('tab', { name: '场景', exact: true }).click()
  const observerStory = observerWorkspace.getByTestId('run-story-panel')
  await expect(observerStory).toContainText('Station')
  const changedPlan = { ...plan, scenes: plan.scenes.map(scene => ({ ...scene, title: scene.id === 'arrival' ? 'Updated station' : scene.title })) }
  expect((await request.post(`${root}/plan`, { headers, data: { run_id: initial.run_id, revision: 1, plan: changedPlan } })).ok()).toBe(true)
  await expect(observerStory).toContainText('Updated station')
  if (!await workspace.isVisible()) await page.getByTestId('play-gm-toggle').first().click()
  await workspace.getByRole('tab', { name: '场景', exact: true }).click()
  const panel = workspace.getByTestId('run-finale')
  await panel.getByRole('button', { name: '准备结束本次冒险', exact: true }).click()
  await expect(panel.getByLabel('公开尾声', { exact: true })).toBeVisible()
  await expect(publicFinale).toContainText('GM 正在准备')
  await expect(observer.locator('.composer')).toHaveCount(0)
  await expect(observer.locator('.table-notice')).toHaveCount(0)
  const blocked = await request.post(`/api/games/${encodeURIComponent(key)}/action`, { headers, data: { text: 'Act after freeze' } })
  expect(blocked.status()).toBe(409)
  await panel.getByRole('button', { name: '取消结团，继续游玩', exact: true }).click()
  await expect(panel.getByRole('button', { name: '准备结束本次冒险', exact: true })).toBeVisible()
  await panel.getByRole('button', { name: '准备结束本次冒险', exact: true }).click()
  await panel.getByLabel('公开尾声', { exact: true }).fill('调查员平安归来。')
  await panel.getByLabel('公开全程团录', { exact: true }).fill('从开场到结局的公开记录。')
  await panel.getByLabel('GM 私有补充（不会给玩家）', { exact: true }).fill('PRIVATE GM NOTES')
  await panel.getByTestId('review-finale').click()
  await panel.getByLabel('已核对公开材料，确认结束本次冒险', { exact: true }).check()
  await panel.getByTestId('commit-finale').click()
  await expect(panel).toContainText('本次冒险已结束')
  await expect(publicFinale).toContainText('调查员平安归来。')
  await expect(publicFinale).toContainText('本次冒险已结束')
  await observer.close()
  await expect(page.locator('.composer')).toHaveCount(0)
  await expect(page.locator('.table-notice')).toHaveCount(0)
  const exported = await (await request.get(`${root}/export`, { headers })).json()
  expect(exported.epilogue).toBe('调查员平安归来。')
  expect(exported.source_rounds).toContain(1)
  await panel.getByText('角色带入下一次冒险', { exact: true }).click()
  await panel.getByRole('button', { name: '创建下一局（保留旧档案）', exact: true }).click()
  await expect(panel.getByRole('link', { name: '进入下一局', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('run-finale.png'), fullPage: false })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2)).toBe(true)
})
