import { expect, test } from './fixtures'

test('compact launch settings expand on demand and retain choices through the wizard', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#/create')
  const next = page.locator('.create-actions .primary')
  await expect(next).toBeEnabled()
  const rules = page.locator('.create-rule-settings')
  const books = page.getByTestId('create-lorebook-summary')
  await expect(rules).not.toHaveAttribute('open')
  await expect(books).not.toHaveAttribute('open')
  await expect(books.locator('summary')).toContainText(/已选 \d+ 册/)
  await expect(rules.locator('select')).toBeHidden()
  await expect(page.getByTestId('lore-source-mode')).toBeHidden()
  await expect(page.getByText('当前规则没有兼容的冒险能力', { exact: false })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^自由冒险/ })).toHaveAttribute('aria-pressed', 'true')
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: info.outputPath('create-compact.png'), fullPage: true })

  await books.locator('summary').click()
  const source = page.getByTestId('lore-source-mode')
  await expect(source.locator('option')).toHaveCount(3)
  await source.selectOption('reference')
  const reference = page.getByTestId('lore-source-world')
  await expect(reference).toBeVisible()
  await expect(books).toContainText('条目不会复制')
  const referenceId = await reference.inputValue()
  await expect(next).toBeEnabled()
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: info.outputPath('create-books-expanded.png'), fullPage: true })
  await next.click()
  await page.locator('.create-actions').getByRole('button', { name: '上一步', exact: true }).click()
  await expect(source).toHaveValue('reference')
  await expect(reference).toHaveValue(referenceId)
  await expect(books.locator('summary')).toContainText('新世界 · 引用资料')
  await books.locator('summary').click()
  await source.selectOption('__builtin__')
  await expect(next).toBeEnabled()
  const checks = books.locator('input[type=checkbox]')
  for (const checkbox of await checks.all()) await checkbox.uncheck()
  await expect(books.locator('summary')).toContainText('已选 0 册')
  await expect(next).toBeEnabled()
  await books.locator('summary').click()
  await rules.locator('summary').first().click()
  await expect(page.getByRole('combobox', { name: '规则', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await next.click()
  await next.click()
  await next.click()
  await expect(page.locator('.create-confirm-stage')).toBeVisible()
  expect(errors).toEqual([])
})
