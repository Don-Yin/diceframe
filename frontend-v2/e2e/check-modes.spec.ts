import { expect, test } from './fixtures'

test('player requests bonus dice and GM grants them with refresh persistence', async ({ page }, info) => {
  const game = encodeURIComponent(`web|e2e-check-mode-${info.project.name}|web_bot`)
  await page.goto(`/#/play?game=${game}&user=e2e-player&share=1&delegate=1`)
  const panel = page.getByTestId('check-modes')
  const toolDialog = () => page.locator('.check-mode-dialog').first()
  await expect(page.getByTestId('check-mode-trigger')).toBeVisible()
  await page.getByTestId('check-mode-trigger').click()
  await expect(toolDialog()).toBeVisible()
  await expect(page.getByTestId('request-e2e-player')).toBeEnabled()
  await page.getByTestId('request-e2e-player').click()
  await page.getByTestId('mode-reason').fill('使用放大镜仔细检查')
  await page.locator('.check-mode-dialog').getByRole('button', { name: '提交', exact: true }).click()
  await expect(panel).toContainText('等待 GM')
  await expect(page.getByTestId('grant-e2e-player')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(toolDialog()).toHaveCount(0)
  const gmModeResponse = page.waitForResponse(response => {
    const url = new URL(response.url())
    return response.request().method() === 'GET'
      && url.pathname.endsWith('/check-modes')
      && !url.searchParams.has('user')
      && response.status() === 200
  })
  await page.goto(`/#/play?game=${game}`)
  const gmModePayload = await gmModeResponse.then(response => response.json() as Promise<{ is_gm?: boolean }>)
  expect(gmModePayload.is_gm).toBe(true)
  await expect(page.getByRole('button', { name: /^GM 工作台/ })).toBeVisible()
  await page.getByTestId('check-mode-trigger').click()
  await expect(toolDialog()).toBeVisible()
  await expect(page.getByTestId('grant-e2e-player')).toHaveCount(1)
  await expect(toolDialog()).toContainText('使用放大镜仔细检查')
  await page.getByTestId('grant-e2e-player').click()
  await expect(page.getByTestId('mode-reason')).toHaveValue('使用放大镜仔细检查')
  await page.locator('.check-mode-dialog').getByRole('button', { name: '提交', exact: true }).click()
  await expect(toolDialog()).toContainText('已授予')
  await page.reload()
  await page.getByTestId('check-mode-trigger').click()
  await expect(toolDialog()).toBeVisible()
  await expect(page.getByTestId('grant-e2e-player')).toHaveCount(1)
  await expect(toolDialog()).toContainText('GM 授予: 奖励骰')
  expect(await panel.evaluate(el => el.scrollWidth - el.clientWidth)).toBeLessThanOrEqual(1)
  await panel.scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('check-mode-review.png'), fullPage: true })
})
