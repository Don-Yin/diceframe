import { expect, test } from './fixtures'

test('player and Keeper complete Push through real routes and preserve both rolls', async ({ page }, info) => {
  const game = encodeURIComponent(`web|e2e-push-${info.project.name}|web_bot`)
  const panel = page.locator('[data-check-id="push-e2e-player"]')
  await page.goto(`/#/play?game=${game}&user=e2e-player&share=1&delegate=1`)
  await expect(panel.getByTestId('push-request')).toBeVisible()
  await panel.locator('textarea').fill('把灯移到门边检查缝隙')
  await panel.getByTestId('push-request').click()
  await expect(panel).toContainText('等待 GM 审核')
  await expect(panel.getByTestId('push-offer')).toHaveCount(0)
  await expect(panel.getByTestId('push-confirm')).toHaveCount(0)
  await page.reload()
  await expect(panel).toContainText('把灯移到门边检查缝隙')
  await page.goto(`/#/play?game=${game}`)
  await expect(panel.getByTestId('push-offer')).toBeVisible()
  await panel.locator('textarea').fill('惊动楼上的守卫')
  await panel.getByTestId('push-offer').click()
  await expect(panel).toContainText('等待玩家确认风险')
  await expect(panel.getByTestId('push-confirm')).toHaveCount(0)
  await page.goto(`/#/play?game=${game}&user=e2e-player&share=1&delegate=1`)
  await expect(panel.getByTestId('push-confirm')).toBeVisible()
  await expect(panel).toContainText('惊动楼上的守卫')
  await panel.getByTestId('push-confirm').click()
  await expect(panel).toContainText('已完成孤注一掷')
  await expect(panel).toContainText(/80 → \d+/)
  await expect(panel.getByTestId('push-confirm')).toHaveCount(0)
  await page.reload()
  await expect(panel).toContainText('已完成孤注一掷')
  await expect(panel).toContainText('惊动楼上的守卫')
  expect(await panel.evaluate(el => el.scrollWidth - el.clientWidth)).toBeLessThanOrEqual(1)
  await panel.scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('push-review.png'), fullPage: true })
})
